const animeDropdown = document.getElementById("animeSelect");
const output = document.getElementById("output");
genreDropdown.addEventListener("change", function(){
    const selectedGenre = genreDropdown.value;
    animeDropdown.innerHTML =
    '<option value="">Select Anime</option>';
if(selectedGenre === ""){
        return;
    }    animeList[selectedGenre].forEach(function(anime, index){

        animeDropdown.innerHTML += `

            <option value="${index}">
                ${anime.title}
            </option>
        `;
    });
});
document.getElementById("recommendBtn").addEventListener("click", function(){

    const selectedGenre = genreDropdown.value;

    const selectedAnimeIndex = animeDropdown.value;
      if(selectedGenre === "" || selectedAnimeIndex === ""){

        output.innerHTML = `

            <div class="alert alert-warning mt-3">

                Please select both genre and anime.

            </div>
        `;

        return;
    }
 const anime =
    animeList[selectedGenre][selectedAnimeIndex];
  output.innerHTML = `

        <div class="anime-card">

            <h2>${anime.title}</h2>

            <p>${anime.description}</p>

            <img src="${anime.image}" alt="${anime.title}">

        </div>
    `;
});
